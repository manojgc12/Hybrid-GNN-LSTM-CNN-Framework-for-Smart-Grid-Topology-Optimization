def build_network(name: str):
    """Return a pandapower network by name: 'ieee33', 'ieee69', 'ieee85'."""
    name = name.lower().strip()
    if name == "ieee69":
        return create_ieee69()
    if name == "ieee85":
        return create_ieee85()
    return create_ieee33()


